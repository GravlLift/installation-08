#requires -Version 7
<#
.SYNOPSIS
    Regenerates the app's PE resources (cmd\infinite-theater-3d\rsrc_windows_amd64.syso)
    from the Go sources.

.DESCRIPTION
    The display name comes from the appDisplayName constant (window.go) and the version
    from the Version default (serve.go). The script rewrites resources.rc from its
    template, so renaming the app is one edit of the constant plus a rerun of this
    script. The app manifest (app.manifest) is applied to a finished exe separately,
    by tools\embed-manifest.ps1.
    windres (a MinGW resource compiler, on PATH) compiles the .rc into the .syso that
    Go's toolchain links into every Windows/amd64 build.

.PARAMETER Repo
    The repo root (default: the parent of this script's folder).
#>
param(
    [string]$Repo
)

$ErrorActionPreference = 'Stop'
$scriptDir = Split-Path -Parent $PSCommandPath
if (-not $Repo) { $Repo = Split-Path -Parent $scriptDir }
$cmd = Join-Path $Repo 'cmd\infinite-theater-3d'
if (-not (Test-Path $cmd)) { throw "cmd dir not found: $cmd" }

# --- 1. Read the display name from the Go constant.
$windowGo = Get-Content (Join-Path $cmd 'window.go') -Raw
if ($windowGo -notmatch 'appDisplayName\s*=\s*"([^"]+)"') { throw 'the appDisplayName constant was not found in window.go' }
$displayName = $Matches[1]

# --- 2. Read the version from the Version default.
$serveGo = Get-Content (Join-Path $cmd 'serve.go') -Raw
if ($serveGo -notmatch '\bVersion\s*=\s*"([^"]+)"') { throw 'the Version default was not found in serve.go' }
$version = $Matches[1]

# The file version is numeric: the version's first three dotted components, zero-padded
# to four. A trailing tag (a -dev suffix) is dropped.
$components = @()
foreach ($c in ($version -split '[^0-9]+')) {
    if ($components.Count -lt 3 -and $c -match '^\d+$') { $components += [int]$c }
}
while ($components.Count -lt 4) { $components += 0 }
$fileVersion = $components[0..3] -join ','

# --- 3. Rewrite resources.rc from the template.
$rc = @"
// resources.rc - the app's PE resources, GENERATED by tools\resources.ps1 from the
// appDisplayName constant (window.go) and the Version default (serve.go). Do not edit
// it by hand: rename the app by editing the constant, then rerun the script.

// The app manifest (app.manifest) is NOT compiled in here: Go already links a default
// manifest into every exe, and a second name-1 manifest would only sit behind it.
// tools\embed-manifest.ps1 replaces the default with app.manifest after the build.

// App icon: resource ID 1, so Explorer and the taskbar use it as the exe's own icon.
1 ICON "../../assets/icon/installation-08.ico"

1 VERSIONINFO
FILEVERSION $fileVersion
PRODUCTVERSION $fileVersion
FILEOS 0x40004
FILETYPE 0x1
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904B0"
        BEGIN
            VALUE "FileDescription", "$displayName"
            VALUE "FileVersion", "$version"
            VALUE "LegalCopyright", "Licensed under AGPL-3.0; see NOTICE.md."
            VALUE "ProductName", "$displayName"
            VALUE "ProductVersion", "$version"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"@
Set-Content -LiteralPath (Join-Path $cmd 'resources.rc') -Value $rc -Encoding utf8NoBOM

# --- 4. Compile it with windres.
$windres = Get-Command windres.exe -ErrorAction SilentlyContinue
if (-not $windres) { throw 'windres.exe (a MinGW resource compiler) was not found on PATH' }
Push-Location $cmd
try {
    & $windres.Source 'resources.rc' '-O' 'coff' '-o' 'rsrc_windows_amd64.syso'
    if ($LASTEXITCODE -ne 0) { throw "windres failed (exit $LASTEXITCODE)" }
}
finally { Pop-Location }
Write-Host "Regenerated rsrc_windows_amd64.syso for '$displayName' (version $version)."
